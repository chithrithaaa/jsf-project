package com.campus.canteen.model;

import java.io.Serializable;
import java.math.BigDecimal;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.List;

public class Order implements Serializable {
    private static final long serialVersionUID = 1L;

    private int id;
    private String orderNumber;
    private int studentId;
    private String studentName;
    private int vendorId;
    private String vendorName;
    private String counterNumber;
    private BigDecimal totalAmount;
    private String status; // "PLACED", "PREPARING", "READY", "COLLECTED", "CANCELLED"
    private Timestamp orderTime;
    private Timestamp pickupTime;
    private String notes;

    private List<OrderItem> items = new ArrayList<>();

    public Order() {
        this.totalAmount = BigDecimal.ZERO;
        this.status = "PLACED";
    }

    public Order(int id, String orderNumber, int studentId, int vendorId, BigDecimal totalAmount, String status, Timestamp orderTime, String notes) {
        this.id = id;
        this.orderNumber = orderNumber;
        this.studentId = studentId;
        this.vendorId = vendorId;
        this.totalAmount = totalAmount;
        this.status = status;
        this.orderTime = orderTime;
        this.notes = notes;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getOrderNumber() {
        return orderNumber;
    }

    public void setOrderNumber(String orderNumber) {
        this.orderNumber = orderNumber;
    }

    public int getStudentId() {
        return studentId;
    }

    public void setStudentId(int studentId) {
        this.studentId = studentId;
    }

    public String getStudentName() {
        return studentName;
    }

    public void setStudentName(String studentName) {
        this.studentName = studentName;
    }

    public int getVendorId() {
        return vendorId;
    }

    public void setVendorId(int vendorId) {
        this.vendorId = vendorId;
    }

    public String getVendorName() {
        return vendorName;
    }

    public void setVendorName(String vendorName) {
        this.vendorName = vendorName;
    }

    public String getCounterNumber() {
        return counterNumber;
    }

    public void setCounterNumber(String counterNumber) {
        this.counterNumber = counterNumber;
    }

    public BigDecimal getTotalAmount() {
        return totalAmount;
    }

    public void setTotalAmount(BigDecimal totalAmount) {
        this.totalAmount = totalAmount;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public Timestamp getOrderTime() {
        return orderTime;
    }

    public void setOrderTime(Timestamp orderTime) {
        this.orderTime = orderTime;
    }

    public Timestamp getPickupTime() {
        return pickupTime;
    }

    public void setPickupTime(Timestamp pickupTime) {
        this.pickupTime = pickupTime;
    }

    public String getNotes() {
        return notes;
    }

    public void setNotes(String notes) {
        this.notes = notes;
    }

    public List<OrderItem> getItems() {
        return items;
    }

    public void setItems(List<OrderItem> items) {
        this.items = items;
    }

    public boolean isCancellable() {
        return "PLACED".equalsIgnoreCase(status);
    }
}
